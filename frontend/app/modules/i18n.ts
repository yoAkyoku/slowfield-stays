import { cookies, headers } from "next/headers";

export type Locale = "en" | "zh";

// Async because Next 15 made cookies() and headers() return promises; the
// synchronous escape hatch they shipped alongside logs an error per request
// and is removed in Next 16.
export async function getLocale(): Promise<Locale> {
  // 1. What the visitor chose.
  const chosen = (await cookies()).get("site-locale")?.value;
  if (chosen === "zh" || chosen === "en") return chosen;
  // 2. What the site is configured to open in. Middleware resolves this and
  //    publishes it as a header, because the ~70 call sites here have no site
  //    object to hand. Before it existed, every first-time visitor to a
  //    Chinese-first brand landed on the English site regardless of what
  //    default_locale said.
  const configured = (await headers()).get("x-site-default-locale");
  if (configured === "zh" || configured === "en") return configured;
  return "en";
}

